#!/usr/bin/env python3
"""Concatenate public documentation in a deterministic order; never reads local data."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    paths = [ROOT / 'AGENTS.md', ROOT / 'docs/for-ai.md', ROOT / 'docs/SPEC.md']
    paths += [p for p in sorted((ROOT / 'docs').glob('*.md')) if p not in paths]
    paths += sorted((ROOT / 'skills').glob('*/SKILL.md'))
    paths += sorted((ROOT / 'skills').glob('*/references/*.md'))
    paths += [ROOT / 'THIRD_PARTY_NOTICES.md', ROOT / 'SECURITY.md']
    parts = ['# Prophet documentation\n\nGenerated by scripts/gen_llms_full.py from public project documentation.\n']
    for path in paths:
        parts.append('\n---\n\nSource: ' + path.relative_to(ROOT).as_posix() + '\n\n' + path.read_text(encoding='utf-8').rstrip() + '\n')
    (ROOT / 'llms-full.txt').write_text(''.join(parts), encoding='utf-8')


if __name__ == '__main__': main()
